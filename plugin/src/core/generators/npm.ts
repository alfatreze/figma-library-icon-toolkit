import { BuildInput, Files, ns } from './common'

/**
 * npm-ready packages: with "npm packages" switched on, every component package in the export (React, Vue, Svelte, Angular, Web Component)
 * and the SVG folder get a package.json (and the build file it needs), so a folder can be published as it is.
 * ESM only, `sideEffects: false` (the Web Component registers a custom element on import, so it lists that one file instead), types included.
 * The build output is for bundlers (Vite, webpack, esbuild…): relative imports carry no file extension, which is how TypeScript projects write them.
 */

const SCOPE = /^@[a-z0-9][a-z0-9-]{0,40}$/
const LICENSE = /^[A-Za-z0-9.+() -]{1,60}$/

/** the scope and licence come from settings (and from a team config file): anything unexpected falls back instead of reaching package.json */
export const npmScope = (b: BuildInput) => (SCOPE.test(b.settings.npm.scope.trim()) ? b.settings.npm.scope.trim() : '')
export const npmLicense = (b: BuildInput) => (LICENSE.test(b.settings.npm.license.trim()) ? b.settings.npm.license.trim() : 'UNLICENSED')

export const packageName = (b: BuildInput, suffix: string) => `${npmScope(b) ? npmScope(b) + '/' : ''}${ns(b)}-icons-${suffix}`

const json = (o: unknown) => JSON.stringify(o, null, 2) + '\n'

function base(b: BuildInput, suffix: string, description: string): Record<string, unknown> {
  return {
    name: packageName(b, suffix),
    version: b.release?.version ?? '1.0.0',
    description,
    license: npmLicense(b),
    type: 'module',
    sideEffects: false,
    keywords: ['icons', ns(b)]
  }
}

const tsBuild = (extra: Record<string, unknown> = {}) =>
  json({
    compilerOptions: { target: 'ES2020', module: 'ESNext', moduleResolution: 'Bundler', strict: true, declaration: true, skipLibCheck: true, lib: ['ES2020', 'DOM'], outDir: 'dist', rootDir: '.', ...extra },
    include: ['./**/*.ts', './**/*.tsx'],
    exclude: ['dist', 'node_modules']
  })

const distExports = { main: './dist/index.js', module: './dist/index.js', types: './dist/index.d.ts', exports: { '.': { types: './dist/index.d.ts', import: './dist/index.js' }, './package.json': './package.json' } }

const readme = (b: BuildInput, suffix: string, what: string, usage: string, publish = 'npm install && npm publish', publishNote = 'It builds first.') => `# ${packageName(b, suffix)}

${what} Generated by Icon Library Toolkit from Figma (${b.icons.length} icons).

\`\`\`sh
npm install ${packageName(b, suffix)}
\`\`\`

${usage}

The package is ESM with types and \`sideEffects: false\`, so a bundler (Vite, webpack, esbuild…) keeps only the icons you import. Style the icons with the CSS variables \`--${ns(b)}-icon-size\`, \`--${ns(b)}-icon-color\` and \`--${ns(b)}-icon-stroke-width\`.

To publish: \`${publish}\`. ${publishNote} Set the package name, licence and version you want in \`package.json\` first.
`

export function npmFiles(b: BuildInput): Files {
  const f = b.settings.formats
  const n = ns(b)
  const first = b.icons[0]?.name ?? 'home'
  const out: Files = {}
  const C = n.charAt(0).toUpperCase() + n.slice(1).replace(/-([a-z0-9])/g, (_m, c) => c.toUpperCase()) + 'Icon'

  if (f.react) {
    out['react/package.json'] = json({ ...base(b, 'react', `${n} icons as React components`), ...distExports, files: ['dist'], scripts: { build: 'tsc -p tsconfig.build.json', prepublishOnly: 'npm run build' }, peerDependencies: { react: '>=17' }, devDependencies: { '@types/react': '^18.3.0', react: '^18.3.0', typescript: '^5.4.0' } })
    out['react/tsconfig.build.json'] = tsBuild({ jsx: 'react-jsx' })
    out['react/README.md'] = readme(b, 'react', 'React components for the icons.', `\`\`\`tsx\nimport { ${C} } from '${packageName(b, 'react')}';\n\nexport const Demo = () => <${C} name="${first}" size={24} />;\n\`\`\``)
  }
  if (f.vue) {
    out['vue/package.json'] = json({ ...base(b, 'vue', `${n} icons as Vue 3 components`), ...distExports, files: ['dist'], scripts: { build: 'tsc -p tsconfig.build.json', prepublishOnly: 'npm run build' }, peerDependencies: { vue: '>=3.3' }, devDependencies: { typescript: '^5.4.0', vue: '^3.5.0' } })
    out['vue/tsconfig.build.json'] = tsBuild()
    out['vue/README.md'] = readme(b, 'vue', 'Vue 3 components for the icons.', `\`\`\`vue\n<script setup lang="ts">\nimport { ${C} } from '${packageName(b, 'vue')}';\n</script>\n\n<template><${C} name="${first}" :size="24" /></template>\n\`\`\``)
  }
  if (f.svelte) {
    out['svelte/package.json'] = json({
      ...base(b, 'svelte', `${n} icons as Svelte components`),
      svelte: './dist/index.js',
      types: './dist/index.d.ts',
      exports: { '.': { types: './dist/index.d.ts', svelte: './dist/index.js', default: './dist/index.js' }, './package.json': './package.json' },
      files: ['dist'],
      // svelte-package reads this folder, so a previous dist/ must not be read again
      scripts: { build: "node -e \"require('fs').rmSync('dist',{recursive:true,force:true})\" && svelte-package -i . -o dist", prepublishOnly: 'npm run build' },
      peerDependencies: { svelte: '^4.0.0 || ^5.0.0' },
      devDependencies: { '@sveltejs/package': '^2.3.0', svelte: '^5.0.0', typescript: '^5.4.0' }
    })
    out['svelte/tsconfig.json'] = json({ compilerOptions: { target: 'ES2020', module: 'ESNext', moduleResolution: 'Bundler', strict: true, verbatimModuleSyntax: true, isolatedModules: true, skipLibCheck: true, lib: ['ES2020', 'DOM'] }, include: ['./**/*.ts', './**/*.svelte'], exclude: ['dist', 'node_modules'] })
    out['svelte/README.md'] = readme(b, 'svelte', 'Svelte components for the icons (Svelte 4 and 5).', `\`\`\`svelte\n<script lang="ts">\n  import { ${C} } from '${packageName(b, 'svelte')}';\n</script>\n\n<${C} name="${first}" size={24} />\n\`\`\``)
  }
  if (f.angularModern) {
    // Angular 14+ is not packaged. ng-packagr 14 cannot bundle the lazy category chunks (dynamic imports). A package built with ng-packagr 17 links with the
    // Angular 14 linker, but its typings use the Angular 16+ input metadata, so Angular 14's strict template check no longer sees the inputs (checked).
    out['angular/package.json'] = json({
      ...base(b, 'angular', `${n} icons as Angular 17.1+ components`),
      scripts: { build: 'ng-packagr -p ng-package.json', release: 'npm run build && npm publish ./dist' },
      peerDependencies: { '@angular/common': '>=17.1.0', '@angular/core': '>=17.1.0', '@angular/platform-browser': '>=17.1.0' },
      dependencies: { tslib: '^2.6.0' },
      devDependencies: { '@angular/common': '^17.1.0', '@angular/compiler': '^17.1.0', '@angular/compiler-cli': '^17.1.0', '@angular/core': '^17.1.0', '@angular/platform-browser': '^17.1.0', 'ng-packagr': '^17.1.0', typescript: '~5.3.0' }
    })
    out['angular/ng-package.json'] = json({ $schema: './node_modules/ng-packagr/ng-package.schema.json', dest: 'dist', lib: { entryFile: 'index.ts' } })
    out['angular/README.md'] = readme(b, 'angular', 'Angular 17.1+ components for the icons.', `Add \`${C}\` to the component's \`imports\` and use \`<${n}-icon name="${first}"></${n}-icon>\` (see the export's README for the sprite and registry options).`, 'npm install && npm run release', 'It builds with ng-packagr and publishes the build output (`dist/`), not this folder.')
  }
  if (f.webComponent) {
    out['web-component/package.json'] = json({
      ...base(b, 'web-component', `${n} icons as a framework-free custom element`),
      sideEffects: [`./${n}-icon.js`],
      main: `./${n}-icon.js`,
      module: `./${n}-icon.js`,
      types: `./${n}-icon.d.ts`,
      exports: { '.': { types: `./${n}-icon.d.ts`, import: `./${n}-icon.js` }, './package.json': './package.json' },
      files: [`${n}-icon.js`, `${n}-icon.d.ts`, 'README.md']
    })
  }
  if (f.svg) {
    out['svg/package.json'] = json({ ...base(b, 'svg', `${n} icons as themeable SVG files`), exports: { './*.svg': './*.svg', './package.json': './package.json' }, files: ['*.svg', '**/*.svg'] })
  }
  return out
}
